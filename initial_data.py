async def populate_initial_data():
    """ملء البيانات الأولية إذا كانت قاعدة البيانات فارغة (INSERT OR IGNORE)"""
    dm = get_data_manager()

    # --- التخصصات ---
    for spec in INITIAL_SPECS:
        await dm.add_specialization(spec)

    # --- الخدمات ---
    existing_prices = await dm.get_prices()
    if not existing_prices:
        for name, price in INITIAL_SERVICES_PRICES.items():
            await dm.set_service_price(name, price)

    # الخدمتان متاحتان لكل تخصص
    for spec in INITIAL_SPECS:
        for service in INITIAL_SERVICES_PRICES:
            await dm.link_service_to_spec(spec, service)

    # --- الكتل والمواد ---
    existing_blocks = await dm.get_all_blocks_count()
    if existing_blocks == 0:
        all_courses = set()
        for spec, blocks in INITIAL_SPEC_BLOCKS.items():
            for block_name, courses in blocks.items():
                await dm.add_block_to_spec(spec, block_name)
                for course in courses:
                    all_courses.add(course)
        # القائمة الرئيسية أولاً (قيد FOREIGN KEY)
        for c in all_courses:
            await dm.add_course(c)
        # ثم ربط المواد بالكتل
        for spec, blocks in INITIAL_SPEC_BLOCKS.items():
            for block_name, courses in blocks.items():
                for course in courses:
                    await dm.add_course_to_block(spec, block_name, course, is_active=True)
        logger.info(f"Initial data: {len(all_courses)} courses in "
                    f"{sum(len(b) for b in INITIAL_SPEC_BLOCKS.values())} blocks")

    # --- طرق الدفع ---
    if not await dm.get_payment_methods():
        for name, info in INITIAL_PAYMENT_METHODS.items():
            await dm.add_payment_method(
                name=name, details=info['details'],
                image_file_id=info.get('image_file_id'))
